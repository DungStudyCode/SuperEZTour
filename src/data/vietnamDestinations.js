/**
 * Filter destinations by region
 * @param {'all' | 'north' | 'central' | 'south'} regionId
 */
export function getDestinationsByRegion(regionId) {
  if (!regionId || regionId === 'all') {
    return VIETNAM_DESTINATIONS;
  }
  return VIETNAM_DESTINATIONS.filter((d) => d.region === regionId);
}

/**
 * Search destinations by keyword (Korean, English, Vietnamese, or aliases)
 * @param {string} rawQuery
 */
export function searchVietnamDestinations(rawQuery) {
  const query = (rawQuery || '').toLowerCase().trim();
  if (!query) return VIETNAM_DESTINATIONS;

  return VIETNAM_DESTINATIONS.filter((d) => {
    if (d.nameKr && d.nameKr.toLowerCase().includes(query)) return true;
    if (d.name && d.name.toLowerCase().includes(query)) return true;
    if (d.nameVi && d.nameVi.toLowerCase().includes(query)) return true;
    if (d.slug && d.slug.toLowerCase().includes(query)) return true;
    if (d.regionKr && d.regionKr.toLowerCase().includes(query)) return true;
    if (d.regionVi && d.regionVi.toLowerCase().includes(query)) return true;
    if (d.tagline && d.tagline.toLowerCase().includes(query)) return true;
    if (d.taglineVi && d.taglineVi.toLowerCase().includes(query)) return true;
    if (d.aliases && d.aliases.some((a) => a.toLowerCase().includes(query))) return true;
    return false;
  });
}

